//! tau-memory's Unicode tables (`plugins/tau-memory/src/unicode.luau`),
//! written from what the Rust it replaced reads: `char::is_alphanumeric`
//! and `to_lowercase` for the words it searches by, and the regex crate's
//! `\w`, `\s` and case folding for its secret and instruction patterns.
//! The file is made from these, never by hand: `BLESS=1` writes it again.

use std::fmt::Write as _;

use regex::Regex;

/// Where the tables live, in the checkout.
fn path() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../plugins/tau-memory/src/unicode.luau")
}

fn chars() -> impl Iterator<Item = char> {
    (0..=0x10FFFF_u32).filter_map(char::from_u32)
}

/// The ranges of code points `keep` holds, as `lo, hi` pairs.
fn ranges(keep: impl Fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut out: Vec<(u32, u32)> = Vec::new();
    for c in chars().filter(|c| keep(*c)) {
        let code = u32::from(c);
        match out.last_mut() {
            Some((_, hi)) if *hi + 1 == code => *hi = code,
            _ => out.push((code, code)),
        }
    }
    out
}

fn table(out: &mut String, name: &str, what: &str, ranges: &[(u32, u32)]) {
    writeln!(out, "-- {what}: inclusive ranges, low then high.").unwrap();
    writeln!(out, "M.{name} = {{").unwrap();
    let mut line = String::from("\t");
    for (lo, hi) in ranges {
        let pair = format!("{lo}, {hi}, ");
        if line.len() + pair.len() > 90 {
            writeln!(out, "{}", line.trim_end()).unwrap();
            line = String::from("\t");
        }
        line.push_str(&pair);
    }
    writeln!(out, "{}", line.trim_end()).unwrap();
    writeln!(out, "}}\n").unwrap();
}

fn lower(text: &str) -> String {
    text.to_lowercase()
}

/// The file as these tables make it.
fn generated() -> String {
    let word = Regex::new(r"^\w$").unwrap();
    let space = Regex::new(r"^\s$").unwrap();
    let one = |re: &Regex, c: char| re.is_match(c.encode_utf8(&mut [0; 4]));
    // Rust's trim and the regex crate's \s read the same property.
    for c in chars() {
        assert_eq!(c.is_whitespace(), one(&space, c), "{c:?}");
    }
    let in_words = |c: char| c.is_alphanumeric() || c == '_';
    let mut out = String::from(
        "-- Generated by tau-built-in-tests (tests/memory/unicode.rs) from Rust's\n\
         -- char tables and the regex crate's; `BLESS=1` writes it again. Not by\n\
         -- hand. Each table of ranges is read by `M.has`.\n\
         local M = {}\n\n",
    );
    table(
        &mut out,
        "ALNUM",
        "What `char::is_alphanumeric` holds: the letters and digits of words",
        &ranges(char::is_alphanumeric),
    );
    table(
        &mut out,
        "WORD",
        "What the regex crate's `\\w` matches, for `\\b`",
        &ranges(|c| one(&word, c)),
    );
    table(
        &mut out,
        "SPACE",
        "White space, as `\\s` and `trim` read it",
        &ranges(char::is_whitespace),
    );
    // Final sigma: Σ lowers to ς after a cased character (case-ignorable
    // ones skipped) with none after it. Only characters of words matter.
    let cased = |c: char| lower(&format!("{c}Σ")).ends_with('ς');
    let ignorable =
        |c: char| lower(&format!("a{c}Σ")).ends_with('ς') && !cased(c);
    table(
        &mut out,
        "CASED",
        "Characters of words that are cased and not case-ignorable",
        &ranges(|c| in_words(c) && cased(c)),
    );
    table(
        &mut out,
        "IGNORABLE",
        "Characters of words that are case-ignorable",
        &ranges(|c| in_words(c) && ignorable(c)),
    );
    // Lowercase: runs of one delta, every code point or every other.
    let mut runs: Vec<(u32, u32, u32, i64)> = Vec::new();
    let mut expand: Vec<(u32, String)> = Vec::new();
    for c in chars().filter(|c| in_words(*c) || *c == 'Σ') {
        let mut lowered = c.to_lowercase();
        let first = lowered.next().unwrap();
        if lowered.next().is_some() {
            expand.push((u32::from(c), c.to_lowercase().collect()));
            continue;
        }
        if first == c {
            continue;
        }
        let code = u32::from(c);
        let delta = i64::from(u32::from(first)) - i64::from(code);
        // A run takes the next code point of its delta at its step; a run
        // of one takes one a step of 1 or 2 away.
        if let Some(run) = runs.last_mut() {
            let (lo, hi, step, d) = *run;
            let gap = code - hi;
            let fits = if step == 0 { gap <= 2 } else { gap == step };
            if d == delta && fits {
                *run = (lo, code, gap, d);
                continue;
            }
        }
        runs.push((code, code, 0, delta));
    }
    writeln!(
        out,
        "-- What `to_lowercase` maps a character of a word to: `lo, hi, step,\n\
         -- delta`, each code point from lo to hi, step apart, plus delta."
    )
    .unwrap();
    writeln!(out, "M.LOWER = {{").unwrap();
    for (lo, hi, step, delta) in &runs {
        writeln!(out, "\t{lo}, {hi}, {}, {delta},", (*step).max(1)).unwrap();
    }
    writeln!(out, "}}\n").unwrap();
    writeln!(out, "-- Those it maps to more than one.").unwrap();
    writeln!(out, "M.EXPAND = {{").unwrap();
    for (code, text) in &expand {
        let escaped: String = text
            .chars()
            .map(|c| format!("\\u{{{:x}}}", u32::from(c)))
            .collect();
        writeln!(out, "\t[{code}] = \"{escaped}\",").unwrap();
    }
    writeln!(out, "}}\n").unwrap();
    // `(?i)`: what else each ASCII letter matches.
    writeln!(
        out,
        "-- What else `(?i)` matches for an ASCII letter, by code point: the\n\
         -- letter, lowercase."
    )
    .unwrap();
    writeln!(out, "M.FOLD = {{").unwrap();
    for letter in 'a'..='z' {
        let re = Regex::new(&format!("(?i)^{letter}$")).unwrap();
        for c in chars().filter(|c| !c.is_ascii() && one(&re, *c)) {
            writeln!(out, "\t[{}] = \"{letter}\",", u32::from(c)).unwrap();
        }
    }
    writeln!(out, "}}\n").unwrap();
    out.push_str(
        "-- Whether `code` is in `ranges`.\n\
         function M.has(ranges, code)\n\
         \tlocal lo, hi = 1, #ranges // 2\n\
         \twhile lo <= hi do\n\
         \t\tlocal mid = (lo + hi) // 2\n\
         \t\tif code < ranges[2 * mid - 1] then\n\
         \t\t\thi = mid - 1\n\
         \t\telseif code > ranges[2 * mid] then\n\
         \t\t\tlo = mid + 1\n\
         \t\telse\n\
         \t\t\treturn true\n\
         \t\tend\n\
         \tend\n\
         \treturn false\n\
         end\n\n\
         -- What `to_lowercase` maps `code` to, as text.\n\
         function M.lower(code)\n\
         \tif M.EXPAND[code] then\n\
         \t\treturn M.EXPAND[code]\n\
         \tend\n\
         \tlocal lower = M.LOWER\n\
         \tlocal lo, hi = 1, #lower // 4\n\
         \twhile lo <= hi do\n\
         \t\tlocal mid = (lo + hi) // 2\n\
         \t\tlocal at = 4 * mid - 3\n\
         \t\tif code < lower[at] then\n\
         \t\t\thi = mid - 1\n\
         \t\telseif code > lower[at + 1] then\n\
         \t\t\tlo = mid + 1\n\
         \t\telse\n\
         \t\t\tif (code - lower[at]) % lower[at + 2] == 0 then\n\
         \t\t\t\treturn utf8.char(code + lower[at + 3])\n\
         \t\t\tend\n\
         \t\t\tbreak\n\
         \t\tend\n\
         \tend\n\
         \treturn utf8.char(code)\n\
         end\n\n\
         return M\n",
    );
    out
}

#[test]
fn the_tables_are_rusts() {
    let want = generated();
    if std::env::var_os("BLESS").is_some() {
        std::fs::write(path(), &want).unwrap();
        return;
    }
    let got = std::fs::read_to_string(path()).unwrap_or_default();
    assert!(
        got == want,
        "plugins/tau-memory/src/unicode.luau is not what Rust's tables make: \
         run this test with BLESS=1"
    );
}
